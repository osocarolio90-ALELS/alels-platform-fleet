function exportPdf(
  rows: TripLogRow[],
  columns: ExportColumn[],
  imei: string,
  selectionCount: number,
  generated: string,
  logoJpeg: Uint8Array | null,
) {
  const tableLines = [
    columns.map(column => column.label).join(" | "),
    ...rows.map(row => columns.map(column => column.value(row)).join(" | ")),
  ];
  const pageSize = 34;
  const pages: string[][] = [];
  for (let offset = 0; offset < tableLines.length; offset += pageSize) pages.push(tableLines.slice(offset, offset + pageSize));
  if (!pages.length) pages.push([]);

  const objects: string[] = [];
  const binaryObjects = new Map<number, Uint8Array>();
  const pageRefs: number[] = [];
  const fontObject = 3;
  objects[fontObject] = `<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>`;
  const boldFontObject = 4;
  objects[boldFontObject] = `<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>`;

  let imageObject = 0;
  if (logoJpeg) {
    imageObject = 5;
    binaryObjects.set(imageObject, logoJpeg);
  }

  let nextObject = imageObject ? 6 : 5;
  pages.forEach((pageLines, pageIndex) => {
    const header = [
      `BT /F2 15 Tf 76 548 Td (${pdf(COMPANY)}) Tj ET`,
      `BT /F1 10 Tf 76 532 Td (${pdf(DOCUMENT_TITLE)}) Tj ET`,
      `0.008 0.518 0.780 RG 28 518 m 814 518 l S`,
      `BT /F1 8 Tf 28 503 Td (${pdf(`Device IMEI: ${imei}   |   Selected Trip/Stop: ${selectionCount}   |   Generated: ${generated}`)}) Tj ET`,
    ];
    if (imageObject) header.unshift(`q 44 0 0 44 28 525 cm /Im1 Do Q`);

    const body = `BT /F1 6 Tf 28 485 Td ${pageLines.map((line, index) => `${index ? "0 -12 Td " : ""}(${pdf(line.slice(0, 220))}) Tj`).join(" ")} ET`;
    const footer = `BT /F1 7 Tf 28 18 Td (${pdf(`Generated by ALELS Platform | Page ${pageIndex + 1} of ${pages.length}`)}) Tj ET`;
    const content = `${header.join("\n")}\n${body}\n${footer}`;
    const contentObject = nextObject++;
    objects[contentObject] = `<< /Length ${byteLength(content)} >>\nstream\n${content}\nendstream`;
    const pageObject = nextObject++;
    pageRefs.push(pageObject);
    const imageResource = imageObject ? ` /XObject << /Im1 ${imageObject} 0 R >>` : "";
    objects[pageObject] = `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 842 595] /Resources << /Font << /F1 ${fontObject} 0 R /F2 ${boldFontObject} 0 R >>${imageResource} >> /Contents ${contentObject} 0 R >>`;
  });

  objects[1] = `<< /Type /Catalog /Pages 2 0 R >>`;
  objects[2] = `<< /Type /Pages /Kids [${pageRefs.map(ref => `${ref} 0 R`).join(" ")}] /Count ${pageRefs.length} >>`;
  if (imageObject && logoJpeg) {
    objects[imageObject] = `<< /Type /XObject /Subtype /Image /Width 600 /Height 400 /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode /Length ${logoJpeg.length} >>`;
  }

  save(new Blob([buildPdf(objects, binaryObjects)], { type: "application/pdf" }), `alels-device-log-${imei}.pdf`);
}

async function loadAlelsLogo(): Promise<{ png: Uint8Array | null; jpeg: Uint8Array | null }> {
  const png = await fetchFirstAsset([LOGO_URL, LOGO_FALLBACK_URL]);
  if (!png) return { png: null, jpeg: null };
  try {
    const blob = new Blob([png], { type: "image/png" });
    const image = await createImageBitmap(blob);
    const canvas = document.createElement("canvas");
    canvas.width = 600;
    canvas.height = 400;
    const context = canvas.getContext("2d");
    if (!context) return { png, jpeg: null };
    context.fillStyle = "#ffffff";
    context.fillRect(0, 0, canvas.width, canvas.height);
    const scale = Math.min(canvas.width / image.width, canvas.height / image.height);
    const width = image.width * scale;
    const height = image.height * scale;
    context.drawImage(image, (canvas.width - width) / 2, (canvas.height - height) / 2, width, height);
    image.close();
    const jpegBlob = await new Promise<Blob | null>(resolve => canvas.toBlob(resolve, "image/jpeg", 0.9));
    return { png, jpeg: jpegBlob ? new Uint8Array(await jpegBlob.arrayBuffer()) : null };
  } catch {
    return { png, jpeg: null };
  }
}

async function fetchFirstAsset(urls: string[]) {
  for (const url of urls) {
    try {
      const response = await fetch(url, { cache: "force-cache" });
      if (response.ok) return new Uint8Array(await response.arrayBuffer());
    } catch { /* use next official asset candidate */ }
  }
  return null;
}

function buildPdf(objects: string[], binaryObjects: Map<number, Uint8Array>) {
  const encoder = new TextEncoder();
  const parts: Uint8Array[] = [encoder.encode("%PDF-1.4\n")];
  const offsets: number[] = [0];
  let length = parts[0].length;
  for (let index = 1; index < objects.length; index++) {
    if (!objects[index]) continue;
    offsets[index] = length;
    const binary = binaryObjects.get(index);
    if (binary) {
      const head = encoder.encode(`${index} 0 obj\n${objects[index]}\nstream\n`);
      const tail = encoder.encode("\nendstream\nendobj\n");
      parts.push(head, binary, tail);
      length += head.length + binary.length + tail.length;
    } else {
      const part = encoder.encode(`${index} 0 obj\n${objects[index]}\nendobj\n`);
      parts.push(part);
      length += part.length;
    }
  }
  const xrefOffset = length;
  let xref = `xref\n0 ${objects.length}\n0000000000 65535 f \n`;
  for (let index = 1; index < objects.length; index++) xref += `${String(offsets[index] || 0).padStart(10, "0")} 00000 n \n`;
  xref += `trailer\n<< /Size ${objects.length} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;
  parts.push(encoder.encode(xref));
  const total = parts.reduce((sum, part) => sum + part.length, 0);
  const output = new Uint8Array(total);
  let cursor = 0;
  parts.forEach(part => { output.set(part, cursor); cursor += part.length; });
  return output;
}

function zipStored(files: Record<string, string | Uint8Array>) {
  const encoder = new TextEncoder();
  const localParts: Uint8Array[] = [];
  const centralParts: Uint8Array[] = [];
  let offset = 0;
  for (const [name, content] of Object.entries(files)) {
    const nameBytes = encoder.encode(name);
    const data = typeof content === "string" ? encoder.encode(content) : content;
    const crc = crc32(data);
    const local = new Uint8Array(30 + nameBytes.length + data.length);
    const view = new DataView(local.buffer);
    view.setUint32(0, 0x04034b50, true); view.setUint16(4, 20, true); view.setUint16(6, 0, true); view.setUint16(8, 0, true);
    view.setUint32(14, crc, true); view.setUint32(18, data.length, true); view.setUint32(22, data.length, true); view.setUint16(26, nameBytes.length, true);
    local.set(nameBytes, 30); local.set(data, 30 + nameBytes.length);
    localParts.push(local);
    const central = new Uint8Array(46 + nameBytes.length);
    const cv = new DataView(central.buffer);
    cv.setUint32(0, 0x02014b50, true); cv.setUint16(4, 20, true); cv.setUint16(6, 20, true); cv.setUint32(16, crc, true);
    cv.setUint32(20, data.length, true); cv.setUint32(24, data.length, true); cv.setUint16(28, nameBytes.length, true); cv.setUint32(42, offset, true);
    central.set(nameBytes, 46); centralParts.push(central); offset += local.length;
  }
  const centralLength = centralParts.reduce((sum, part) => sum + part.length, 0);
  const end = new Uint8Array(22);
  const ev = new DataView(end.buffer);
  ev.setUint32(0, 0x06054b50, true); ev.setUint16(8, centralParts.length, true); ev.setUint16(10, centralParts.length, true);
  ev.setUint32(12, centralLength, true); ev.setUint32(16, offset, true);
  const all = [...localParts, ...centralParts, end];
  const total = all.reduce((sum, part) => sum + part.length, 0);
  const output = new Uint8Array(total);
  let cursor = 0;
  all.forEach(part => { output.set(part, cursor); cursor += part.length; });
  return output;
}

function crc32(data: Uint8Array) {
  let crc = 0xffffffff;
  for (const byte of data) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1));
  }
  return (crc ^ 0xffffffff) >>> 0;
}
function columnName(index: number) {
  let value = index + 1;
  let result = "";
  while (value) { value--; result = String.fromCharCode(65 + (value % 26)) + result; value = Math.floor(value / 26); }
  return result;
}
function byteLength(value: string) { return new TextEncoder().encode(value).length; }
function xml(value: string) { return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;"); }
function pdf(value: string) { return value.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)").replace(/[^\x20-\x7E]/g, "?"); }
function save(blob: Blob, name: string) {
  const link = document.createElement("a");
  link.href = URL.createObjectURL(blob);
  link.download = name;
  link.click();
  setTimeout(() => URL.revokeObjectURL(link.href), 1000);
}
