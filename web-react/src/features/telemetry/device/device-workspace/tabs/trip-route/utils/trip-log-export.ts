import type { TripLogRow } from "../types/device-workspace-trip-route";

export type ExportColumn = { label: string; value: (row: TripLogRow) => string };
export type ExportFormat = "xlsx" | "csv" | "pdf";

const COMPANY = "ALELS TECH INDONESIA";
const DOCUMENT_TITLE = "Device Log History";
const LOGO_URL = "/assets/logo-card.png";
const LOGO_FALLBACK_URL = "/assets/alels-mark-light.png";

export async function exportTripLog(format: ExportFormat, rows: TripLogRow[], columns: ExportColumn[], imei: string, selectionCount: number) {
  const generated = new Date().toLocaleString("id-ID");
  if (format === "csv") return exportCsv(rows, columns, imei, selectionCount, generated);

  const logo = await loadAlelsLogo();
  if (format === "xlsx") return exportXlsx(rows, columns, imei, selectionCount, generated, logo.png);
  return exportPdf(rows, columns, imei, selectionCount, generated, logo.jpeg);
}

function exportCsv(rows: TripLogRow[], columns: ExportColumn[], imei: string, selectionCount: number, generated: string) {
  const quote = (value: string) => `"${value.replace(/"/g, '""')}"`;
  const lines = [
    quote(COMPANY),
    quote(DOCUMENT_TITLE),
    `${quote("Device IMEI")},${quote(imei)}`,
    `${quote("Selected Trip/Stop")},${quote(String(selectionCount))}`,
    `${quote("Generated")},${quote(generated)}`,
    quote("Generated by ALELS Platform"),
    "",
    columns.map(column => quote(column.label)).join(","),
    ...rows.map(row => columns.map(column => quote(column.value(row))).join(",")),
  ];
  save(new Blob(["\ufeff", lines.join("\r\n")], { type: "text/csv;charset=utf-8" }), `alels-device-log-${imei}.csv`);
}

